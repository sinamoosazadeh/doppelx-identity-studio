#!/usr/bin/env node
/**
 * Keep the executable runtime in one auditable source of truth.
 *
 * Canonical source: android/app/assets/js/spoof.js
 * Mirrors:          web/doppel-extension/spoof.js
 *                   android/app/assets/js/spoof-src.js (embedded string)
 *
 * Usage:
 *   node scripts/sync-runtime.mjs          # write mirrors
 *   node scripts/sync-runtime.mjs --check  # fail if a mirror is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const canonicalPath = path.join(root, 'android/app/assets/js/spoof.js');
const extensionPath = path.join(root, 'web/doppel-extension/spoof.js');
const embeddedPath = path.join(root, 'android/app/assets/js/spoof-src.js');
const checkOnly = process.argv.includes('--check');

const canonical = readFileSync(canonicalPath, 'utf8');
const embedded = `/* Auto-generated by scripts/sync-runtime.mjs. Do not edit directly. */\nwindow.__SPOOF_SRC__ = ${JSON.stringify(canonical)};\n`;
const targets = [
  [extensionPath, canonical],
  [embeddedPath, embedded],
];

let stale = false;
for (const [target, expected] of targets) {
  let actual = '';
  try { actual = readFileSync(target, 'utf8'); } catch { /* written below */ }
  if (actual === expected) continue;
  stale = true;
  if (checkOnly) {
    console.error(`stale generated/runtime mirror: ${path.relative(root, target)}`);
  } else {
    writeFileSync(target, expected, 'utf8');
    console.log(`synced ${path.relative(root, target)}`);
  }
}

if (checkOnly && stale) process.exit(1);
if (!stale) console.log('runtime mirrors are synchronized');
